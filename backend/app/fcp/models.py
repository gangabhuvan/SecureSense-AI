class FCPRelationshipSignal(BaseModel):
    """
    Compact relationship-derived signal surfaced by the FCP.

    A relationship signal describes contextual graph evidence
    associated with an STG subject entity.

    Relationship-derived evidence is intentionally kept
    separate from direct entity reputation and sender
    authentication.

    A relationship does NOT by itself establish that the
    subject entity is malicious, trusted, or authenticated.
    """

    relationship_type: str = "UNKNOWN"

    neighbour_node_id: str = ""

    neighbour_type: str = "Unknown"

    neighbour_value: str = ""

    neighbour_classification: str = "Unknown"

    neighbour_risk_score: Optional[float] = None

    risk_contribution: float = 0.0

    trust_contribution: float = 0.0

    confidence: float = 0.0

    evidence_ids: List[str] = Field(
        default_factory=list
    )

    ledger_ids: List[str] = Field(
        default_factory=list
    )

    reason: str = ""


class FCPRelationshipContextItem(BaseModel):
    """
    Relationship-derived contextual intelligence for one
    STG subject entity.

    This model intentionally preserves per-entity context.

    Scores belonging to unrelated entities must not be
    averaged together into an artificial global graph score.
    """

    subject_node_id: str

    available: bool = False

    contextual_risk_score: Optional[float] = None

    contextual_trust_score: Optional[float] = None

    confidence: float = 0.0

    classification: str = "Unknown"

    relationships_analysed: int = 0

    contributing_relationships: int = 0

    high_risk_neighbours: int = 0

    suspicious_neighbours: int = 0

    trusted_neighbours: int = 0

    signals: List[
        FCPRelationshipSignal
    ] = Field(
        default_factory=list
    )

    evidence_ids: List[str] = Field(
        default_factory=list
    )

    ledger_ids: List[str] = Field(
        default_factory=list
    )

    reasons: List[str] = Field(
        default_factory=list
    )

    summary: str = (
        "No relationship-derived contextual intelligence "
        "is currently available."
    )


class FCPRelationshipContext(BaseModel):
    """
    Compact relationship-derived STG context stored in the
    Financial Communication Passport.

    Relationship intelligence remains a separate contextual
    dimension from:

    - communication-level security risk
    - direct historical entity reputation
    - sender authenticity / AVE verification

    Per-entity relationship contexts are retained separately.
    No artificial global relationship risk/trust average is
    produced.

    Relationship-derived evidence may strengthen contextual
    caution, but it must never authenticate a sender or
    silently override the trained communication-level
    security decision.
    """

    available: bool = False

    contexts_analysed: int = 0

    contexts_available: int = 0

    total_signals: int = 0

    contexts: List[
        FCPRelationshipContextItem
    ] = Field(
        default_factory=list
    )

    evidence_ids: List[str] = Field(
        default_factory=list
    )

    ledger_ids: List[str] = Field(
        default_factory=list
    )

    summary: str = (
        "No relationship-derived STG context is currently "
        "available."
    )

    contextual_role: str = (
        "Relationship-derived graph context only. "
        "Does not create direct entity-security evidence, "
        "authenticate the sender, or override "
        "communication-level security analysis."
    )


