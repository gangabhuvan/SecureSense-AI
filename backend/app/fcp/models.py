"""
models.py

Financial Communication Passport (FCP) models.

The FCP is the standardized trust object generated by
SecureSense AI from intelligence, verification, historical
graph context and explainable evidence.
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field


class VerificationStatus(BaseModel):
    """
    Results from the Authenticity Verification Engine (AVE).
    """

    official_domain: bool = False
    official_provider: Optional[str] = None
    registered_domain: Optional[str] = None
    official_email: bool = False
    official_phone: bool = False
    official_qr: bool = False
    digital_signature: bool = False
    metadata_consistent: bool = True

    verification_confidence: float = 0.0

    # Important distinction:
    # False indicators do NOT automatically mean verification failed.
    # The verification engine may simply not have run yet.
    status: str = "Not Performed"


class EvidenceSummary(BaseModel):
    """
    Summary of evidence supporting the passport decision.
    """

    total_findings: int = 0

    high_severity: int = 0
    medium_severity: int = 0
    low_severity: int = 0

    evidence_ids: List[str] = Field(
        default_factory=list
    )

    ledger_ids: List[str] = Field(
        default_factory=list
    )

    modules: List[str] = Field(
        default_factory=list
    )


class ExplainableEvidenceItem(BaseModel):
    """
    Human-readable evidence surfaced by the FCP.
    """

    source_module: str

    feature: str

    value: Any

    contribution: float

    direction: str

    strength: float


