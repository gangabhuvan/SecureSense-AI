# Securities Trust Graph Context
# ============================================================

class SecuritiesTrustGraphContext(BaseModel):
    """
    Historical entity-reputation context supplied by the
    Securities Trust Graph (STG).

    This information is intentionally kept separate from:

    - communication-level risk
    - sender authenticity
    - AVE verification

    A trusted entity does NOT authenticate the sender and does
    NOT make suspicious communication content safe.

    Likewise, historical high-risk entity evidence may provide
    additional security context without replacing the trained
    communication-level model decision.

    Relationship-derived context is exposed independently from
    direct entity reputation so that graph associations cannot
    silently become direct security evidence.
    """

    available: bool = False

    reputation_available: bool = False

    classification: str = "Unknown"

    graph_risk_score: Optional[float] = None

    graph_trust_score: Optional[float] = None

    confidence: float = 0.0

    entities_analysed: int = 0

    # --------------------------------------------------------
    # Relationship-Derived Context
    # --------------------------------------------------------
    #
    # Relationship intelligence is intentionally nested under
    # STG but kept separate from direct historical reputation.
    #
    # It must not:
    #
    # - authenticate the sender
    # - create direct reputation evidence
    # - overwrite graph_risk_score
    # - overwrite graph_trust_score
    # - modify communication-level risk
    # --------------------------------------------------------

    relationship_context: Optional[
        FCPRelationshipContext
    ] = None

    evidence_ids: List[str] = Field(
        default_factory=list
    )

    ledger_ids: List[str] = Field(
        default_factory=list
    )

    summary: str = ""

    contextual_role: str = (
        "Historical entity context only. "
        "Does not authenticate the sender or override "
        "communication-level security analysis."
    )


class FinancialCommunicationPassport(BaseModel):
    """
    Standardized Trust Passport for an analysed
    financial communication.
    """

    passport_id: str

    communication_id: Optional[str] = None

    generated_at: datetime = Field(
        default_factory=lambda: datetime.now(
            timezone.utc
        )
    )

    communication_type: str

    claimed_sender: str = "Unknown"

    verified_sender: bool = False

    verification: VerificationStatus

    threat_categories: List[str] = Field(
        default_factory=list
    )

    ai_manipulation_findings: List[str] = Field(
        default_factory=list
    )

    risk_score: float

    risk_level: str

    trust_score: float

    confidence: float

    # --------------------------------------------------------
    # Historical Entity-Reputation Context
    # --------------------------------------------------------
    #
    # STG is intentionally represented as an independent
    # contextual dimension.
    #
    # It must not be interpreted as sender authentication and
    # must not silently modify the trained communication-level
    # risk score.
    #
    # Relationship-derived graph intelligence, when present,
    # is nested inside the STG context and remains separate
    # from direct entity reputation.
    # --------------------------------------------------------

    securities_trust_graph: Optional[
        SecuritiesTrustGraphContext
    ] = None

    evidence: EvidenceSummary

    explainable_evidence: List[
        ExplainableEvidenceItem
    ] = Field(
        default_factory=list
    )

    recommended_action: str